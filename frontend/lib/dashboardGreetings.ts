const DEFAULT_GREETING = DASHBOARD_GREETINGS[0];

export function pickDashboardGreeting(): string {
  if (typeof window !== "undefined" && window.crypto?.getRandomValues) {
    const value = new Uint32Array(1);
    window.crypto.getRandomValues(value);
    return DASHBOARD_GREETINGS[value[0] % DASHBOARD_GREETINGS.length];
  }
  return DASHBOARD_GREETINGS[Math.floor(Math.random() * DASHBOARD_GREETINGS.length)];
}

export function isDashboardGreeting(value: string): boolean {
  return DASHBOARD_GREETINGS.some((greeting) => greeting === value);
}

